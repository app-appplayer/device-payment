/// The remote service, standing in.
///
///   dart run bin/mint.dart keygen
///   dart run bin/mint.dart sign --device stm32.h723 --action locker-4h \
///       --target B12 --session 1 --seconds 14400
///
/// `keygen` writes the key pair once and emits the C initialiser the firmware
/// compiles in. `sign` mints one voucher.
///
/// This is the only place a signing key exists. The node holds the public half
/// and can therefore check a voucher without being able to make one — which is
/// the property the whole arrangement rests on, so the two halves are kept
/// visibly apart rather than in one convenient helper.
///
/// The signed bytes are the fields joined in a fixed order, not a serialised
/// document. A JSON re-encode differing by one space would fail to verify, and
/// worse, a field the device's parser ignores would still have been signed. The
/// device rebuilds this same string from what it read.
library;

import 'dart:convert';
import 'dart:io';

import 'package:cryptography/cryptography.dart';

const _keyFile = 'keys.json';
const _incFile = '../../src/service_pubkey.inc';
/// The device's own key. A DIFFERENT key from the service's, and the reason
/// the two exist is that they prove different things: the service key mints
/// authority, the device key proves which machine is speaking. A device that
/// could mint would be a machine that authorises itself.
const _deviceIncFile = '../../src/device_privkey.inc';

String signedInput({
  required String deviceId,
  required String action,
  required int notBefore,
  required int notAfter,
  required String target,
  required int session,
}) =>
    '$deviceId\n$action\n$notBefore\n$notAfter\n$target\n$session';

Future<void> main(List<String> args) async {
  if (args.isEmpty) {
    stderr.writeln('usage: mint.dart keygen | sign [options]');
    exit(2);
  }
  final algorithm = Ed25519();

  if (args.first == 'keygen') {
    final pair = await algorithm.newKeyPair();
    final priv = await pair.extractPrivateKeyBytes();
    final pub = (await pair.extractPublicKey()).bytes;

    // The device key. Generated here because this tool stands in for the whole
    // remote service, and issuing a device its identity is a service act — the
    // patent calls it provisioning, and the public half is what the service
    // keeps in order to recognise the machine later.
    final devicePair = await algorithm.newKeyPair();
    final devicePriv = await devicePair.extractPrivateKeyBytes();
    final devicePub = (await devicePair.extractPublicKey()).bytes;

    File(_keyFile).writeAsStringSync(
      const JsonEncoder.withIndent('  ').convert({
        'private': base64Url.encode(priv).replaceAll('=', ''),
        'public': base64Url.encode(pub).replaceAll('=', ''),
        // The device's public half. The private half goes into the firmware
        // and is not kept here — a service that holds a device's private key
        // can forge that device.
        'devicePublic': base64Url.encode(devicePub).replaceAll('=', ''),
      }),
    );
    final devHex =
        devicePriv.map((b) => '0x${b.toRadixString(16).padLeft(2, '0')}');
    File(_deviceIncFile).writeAsStringSync(
      "/* Generated by tools/mint_voucher — this device's private key.\n"
      '   Never committed: a published device key is a device anyone can\n'
      '   impersonate. Regenerate with `keygen` and reflash. */\n'
      '${devHex.join(', ')}\n',
    );
    // The firmware compiles the public half in as a flash constant. Emitted
    // rather than pasted so the key on the board and the key here cannot drift.
    final hex = pub.map((b) => '0x${b.toRadixString(16).padLeft(2, '0')}');
    File(_incFile).writeAsStringSync(
      '/* Generated by tools/mint_voucher — the service public key this node\n'
      '   verifies against. Regenerate with `dart run bin/mint.dart keygen`\n'
      '   and reflash; a stale copy here refuses every voucher. */\n'
      '${hex.join(', ')}\n',
    );
    stdout.writeln('wrote $_keyFile, $_incFile and $_deviceIncFile');
    return;
  }

  if (args.first != 'sign') {
    stderr.writeln('unknown command: ${args.first}');
    exit(2);
  }

  String opt(String name, [String? fallback]) {
    final i = args.indexOf('--$name');
    if (i < 0 || i + 1 >= args.length) {
      if (fallback != null) return fallback;
      stderr.writeln('missing --$name');
      exit(2);
    }
    return args[i + 1];
  }

  final keys =
      jsonDecode(File(_keyFile).readAsStringSync()) as Map<String, dynamic>;
  final pair = await algorithm.newKeyPairFromSeed(
    base64Url.decode(_pad(keys['private'] as String)),
  );

  final deviceId = opt('device');
  final action = opt('action');
  final target = opt('target', 'B12');
  final session = int.parse(opt('session'));
  final seconds = int.parse(opt('seconds', '14400'));
  // Wall-clock seconds, because the device judges the interval against the
  // time a phone presented to it — the two have to be the same clock.
  final now = DateTime.now().millisecondsSinceEpoch ~/ 1000;
  final notBefore = int.parse(opt('notBefore', '${now - 5}'));
  final notAfter = int.parse(opt('notAfter', '${notBefore + seconds}'));

  final input = signedInput(
    deviceId: deviceId,
    action: action,
    notBefore: notBefore,
    notAfter: notAfter,
    target: target,
    session: session,
  );
  // The device's assertion, when one is relayed. The service verifies it
  // BEFORE minting anything: §3.2 is what makes the comparison meaningful in
  // both directions, and a service that mints first has verified nothing.
  final assertionArg = _optional(args, 'assertion');
  if (assertionArg != null) {
    final a = jsonDecode(assertionArg) as Map<String, dynamic>;
    final devicePub = SimplePublicKey(
      base64Url.decode(_pad(keys['devicePublic'] as String)),
      type: KeyPairType.ed25519,
    );
    final counter = a['counter'] as int;
    final assertedInput =
        "${a['deviceId']}\n$counter\n${a['nonce']}\n${a['specHash']}";
    final ok = await algorithm.verify(
      utf8.encode(assertedInput),
      signature: Signature(base64Url.decode(_pad(a['sig'] as String)),
          publicKey: devicePub),
    );
    if (!ok) {
      stderr.writeln('refused: the device assertion does not verify');
      exit(3);
    }
    if (a['deviceId'] != deviceId) {
      stderr.writeln('refused: the assertion is from another device');
      exit(3);
    }
    // A counter not exceeding the highest already accepted is an assertion
    // captured earlier and replayed on the device's behalf.
    final seenFile = File('counters.json');
    final seen = seenFile.existsSync()
        ? jsonDecode(seenFile.readAsStringSync()) as Map<String, dynamic>
        : <String, dynamic>{};
    final highest = (seen[deviceId] as int?) ?? 0;
    if (counter <= highest) {
      stderr.writeln('refused: assertion counter $counter was already used');
      exit(3);
    }
    // The declaration the phone relayed must be the one the device signed
    // over. Otherwise a relayer can tell the service about an offer the
    // machine never made.
    final specArg = _optional(args, 'spec');
    if (specArg != null) {
      final digest = await Sha512().hash(utf8.encode(specArg));
      final relayed =
          base64Url.encode(digest.bytes).replaceAll('=', '');
      if (relayed != a['specHash']) {
        stderr.writeln('refused: the relayed declaration is not the one the '
            'device signed');
        exit(3);
      }
    }
    seen[deviceId] = counter;
    seenFile.writeAsStringSync(jsonEncode(seen));
  }

  final signature = await algorithm.sign(utf8.encode(input), keyPair: pair);

  stdout.writeln(jsonEncode({
    'deviceId': deviceId,
    'action': action,
    'notBefore': notBefore,
    'notAfter': notAfter,
    'target': target,
    'session': session,
    'sig': base64Url.encode(signature.bytes).replaceAll('=', ''),
  }));
}

String _pad(String s) => s.padRight((s.length + 3) & ~3, '=');

/// An argument that may be absent, unlike the required ones.
String? _optional(List<String> args, String name) {
  final i = args.indexOf('--$name');
  if (i < 0 || i + 1 >= args.length) return null;
  return args[i + 1];
}
